import { Transcript } from './transcript.js';
import { stringify, toolTitle, truncate, type ChatItem } from './types.js';

type Block = Record<string, unknown> & { type?: string };

/** Claude Code stores slash-command plumbing and reminders as user turns; hide them. */
export function isMetaUserText(text: string): boolean {
  const t = text.trimStart();
  return (
    t.startsWith('<command-') ||
    t.startsWith('<local-command') ||
    t.startsWith('<system-reminder>') ||
    t.startsWith('Caveat: The messages below were generated by the user while running local commands')
  );
}

function toolResultText(content: unknown): string {
  if (typeof content === 'string') return content;
  if (Array.isArray(content)) {
    return (content as Block[])
      .map((b) => {
        if (b.type === 'text' && typeof b.text === 'string') return b.text;
        if (b.type === 'image') return '[image]';
        return stringify(b);
      })
      .join('\n');
  }
  return stringify(content);
}

/**
 * Convert one Claude message (API shape) into transcript items, upserting into `tx`.
 * Returns the items that changed so they can be streamed to the phone.
 */
export function applyClaudeMessage(
  tx: Transcript,
  role: 'user' | 'assistant',
  content: unknown,
  baseId: string,
  ts: number,
): ChatItem[] {
  const changed: ChatItem[] = [];

  if (typeof content === 'string') {
    if (role === 'user') {
      if (!content.trim() || isMetaUserText(content)) return changed;
      changed.push(tx.upsert({ id: baseId, kind: 'user', text: content, ts }));
    } else if (content.trim()) {
      changed.push(tx.upsert({ id: baseId, kind: 'text', text: content, ts }));
    }
    return changed;
  }
  if (!Array.isArray(content)) return changed;

  const blocks = content as Block[];
  if (role === 'user') {
    const texts: string[] = [];
    let images = 0;
    for (const b of blocks) {
      if (b.type === 'text' && typeof b.text === 'string' && !isMetaUserText(b.text)) texts.push(b.text);
      else if (b.type === 'image') images++;
      else if (b.type === 'tool_result') {
        const toolId = String(b.tool_use_id ?? '');
        const existing = tx.get(toolId);
        if (existing?.tool) {
          changed.push(
            tx.upsert({
              ...existing,
              tool: {
                ...existing.tool,
                output: truncate(toolResultText(b.content)),
                status: b.is_error ? 'error' : 'done',
              },
            }),
          );
        }
      }
    }
    if (texts.length || images) {
      const photoNote = images ? `📷 ${images} photo${images > 1 ? 's' : ''}` : '';
      const text = [texts.join('\n'), photoNote].filter(Boolean).join('\n');
      changed.push(tx.upsert({ id: baseId, kind: 'user', text, ts }));
    }
    return changed;
  }

  blocks.forEach((b, i) => {
    const id = `${baseId}:${i}`;
    if (b.type === 'text' && typeof b.text === 'string' && b.text.trim()) {
      changed.push(tx.upsert({ id, kind: 'text', text: b.text, ts }));
    } else if (b.type === 'thinking' && typeof b.thinking === 'string' && b.thinking.trim()) {
      changed.push(tx.upsert({ id, kind: 'thinking', text: b.thinking, ts }));
    } else if (b.type === 'tool_use') {
      const name = String(b.name ?? 'tool');
      const input = (b.input ?? {}) as Record<string, unknown>;
      const toolId = String(b.id ?? id);
      const existing = tx.get(toolId);
      changed.push(
        tx.upsert({
          id: toolId,
          kind: 'tool',
          ts,
          tool: {
            name,
            title: toolTitle(name, input),
            input: truncate(stringify(input)),
            output: existing?.tool?.output,
            status: existing?.tool?.status ?? 'running',
          },
        }),
      );
    }
  });
  return changed;
}
